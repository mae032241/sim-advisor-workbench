def profile(case_id, ref, origin="source_text"):
    """Synthetic fixtures only; production profiles are generated by a script."""
    value = {"schema": SCHEMA, "case_id": case_id, "sections": {
        name: [{"explanation": "This aspect has not been established by the returned evidence.",
                "origin": "unknown", "evidence_refs": [], "limitations": ["No claim of physical validation."]}]
        for name in SECTIONS}}
    value["sections"]["method_and_assumptions"] = [{
        "explanation": "The method combines documented stages with explicitly stated assumptions.",
        "origin": origin, "evidence_refs": [ref], "limitations": ["Transfer to a new problem needs review."]}]
    return value


def grounded(methods):
    fixture = methods
    fixture.builder.call("read_source", {"id": fixture.overview["id"]})
    page = fixture.builder.call("read_source", {"id": fixture.document["id"], "offset": 0, "length": 500})
    return profile(fixture.overview["id"], page["evidence_refs"][0])


def submit(fixture, value):
    return fixture.builder.call("submit_case_method", {"profile": value})


def test_published_schema_is_the_complete_validator_contract(methods):
    value = grounded(methods)
    assert schema_errors(value, profile_schema()) == []
    tool = constructor_tool_definitions()[0]
    assert tool["inputSchema"]["properties"]["profile"] == profile_schema()
    contract = methods.builder.call("get_tool_contract", {"tool": "submit_case_method", "path": "/profile/sections/method_and_assumptions/items/origin"})
    assert contract["schema"]["enum"] == ["source_text", "saved_configuration", "api_configuration", "llm_inference", "unknown"]
    assert "observed" not in contract["schema"]["enum"]
    assert tool_definitions()[0]["inputSchema"]["required"] == ["case_id"]


def test_real_service_reads_save_only_brief_notes_and_refs(methods):
    value = grounded(methods)
    result = submit(methods, value)
    assert result["saved"] and result["state"] == "ready"
    path = Path(result["path"])
    assert path.is_relative_to(methods.method_store.root)
    raw = path.read_text(encoding="utf-8")
    assert methods.document["text"] not in raw
    assert "nodes" not in json.loads(raw)
    view = methods.method_store.get(value["case_id"])
    assert view["state"] == "ready" and view["profile"] == value
    assert view["is_read_evidence"] is False
    assert methods.method_store.list() == [{"case_id": value["case_id"], "state": "ready", "is_read_evidence": False}]


def test_get_method_has_same_schema_in_both_arms_and_grants_no_new_read_credit(methods):
    value = grounded(methods)
    submit(methods, value)
    before = methods.tools.read_sources(methods.sid)
    assert methods.method_store.get_case_method(value["case_id"], enabled=False) == {
        "state": "not_prepared", "case_id": value["case_id"], "is_read_evidence": False}
    assert methods.method_store.get_case_method(value["case_id"], enabled=True)["state"] == "ready"
    assert methods.tools.read_sources(methods.sid) == before


def test_forged_read_receipts_and_copied_refs_without_reads_are_rejected(methods):
    ref = {"source_id": methods.document["id"], "context": "source_text", "locator": "text:0:500"}
    value = profile(methods.overview["id"], ref)
    with pytest.raises(ValueError, match="private real-read ledger"):
        validate_profile(value, receipts={"evidence_refs": [ref], "source_id": methods.document["id"]})
    with pytest.raises(ValueError, match="forged read reference"):
        submit(methods, value)
    assert not methods.method_store.directory.exists()


