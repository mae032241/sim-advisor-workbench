def test_a_frozen_profile_is_never_overwritten(methods):
    value = grounded(methods)
    result = submit(methods, value)
    path = Path(result["path"])
    original = path.read_bytes()
    value["sections"]["method_and_assumptions"][0]["explanation"] = "Changed synthetic note."
    with pytest.raises(FileExistsError, match="fresh experiment directory"):
        submit(methods, value)
    assert path.read_bytes() == original


