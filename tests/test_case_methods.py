def test_unknown_and_llm_inference_cannot_be_labeled_observed(methods):
    value = grounded(methods)
    claim = value["sections"]["evidence_coverage_unknowns"][0]
    claim["origin"] = "observed"
    with pytest.raises(ValueError, match="published schema"):
        submit(methods, value)
    claim["origin"] = "unknown"
    claim["evidence_refs"] = copy.deepcopy(value["sections"]["method_and_assumptions"][0]["evidence_refs"])
    with pytest.raises(ValueError, match="unknown is a gap"):
        submit(methods, value)
    claim["origin"] = "llm_inference"
    claim["explanation"] = "This migration boundary is an interpretation that remains unverified."
    assert submit(methods, value)["saved"]
    assert methods.method_store.get(value["case_id"])["profile"]["sections"]["evidence_coverage_unknowns"][0]["origin"] == "llm_inference"


