@pytest.mark.parametrize('mode', ['overview_and_config', 'tutorial_only', 'configuration_only',
                                  'separate_claims', 'wrong_section', 'direct_origin',
                                  'unread_tutorial', 'joint_claim'])
def test_joint_mode_requires_both_actual_reads_in_one_inference(joint_case, tmp_path, mode):
    fixture = joint_case
    app, args = app_for(fixture), options(tmp_path, fixture.overview['id'])
    args.joint_sources = True
    store = CaseMethodStore(args.output, fixture.provider)
    instances = []

    class JointRuntime:
        def __init__(self, **kwargs):
            self.callback, self.event = kwargs['on_tool'], kwargs['on_event']
            instances.append(self)
        def start(self, **kwargs):
            self.instructions = kwargs['instructions']
            definitions = kwargs['tools']
            submission = next(item for item in definitions if item['name'] == 'submit_case_method')
            assert submission['inputSchema']['properties']['profile'] == profile_schema()
            assert build.JOINT_SOURCE_RULE in submission['description']
            contract = self.callback('get_tool_contract', {'tool': 'submit_case_method',
                                     'path': '/profile/sections/method_and_assumptions/0/evidence_refs'})
            assert build.JOINT_SOURCE_RULE in contract['rules']
            assert json.loads(contract['text'])['items']['properties']['context']['enum'] == [
                'source_text', 'case_configuration']
            return {'thread_id': 'synthetic-joint-thread'}
        def send(self, _text):
            overview = self.callback('read_source', {'id': fixture.overview['id']})
            self.callback('get_case_guide', {'case_id': fixture.overview['id'], 'stage': 'mesh'})
            tutorial = (self.callback('read_source', {'id': fixture.tutorial['id']})
                        if mode not in {'overview_and_config', 'configuration_only', 'unread_tutorial'} else None)
            configuration = (self.callback('read_case_configuration', {'case_id': fixture.overview['id'],
                             'node_path': 'compact:node/3', 'source': 'saved'}) if mode != 'tutorial_only' else None)
            config_ref = configuration['evidence_refs'][0] if configuration else None
            text_ref = tutorial['evidence_refs'][0] if tutorial else overview['evidence_refs'][0]
            if mode == 'unread_tutorial':
                text_ref = {'source_id': fixture.tutorial['id'], 'context': 'source_text',
                            'locator': 'text:0:' + str(len(fixture.tutorial['text']))}
            value = synthetic_profile(fixture.overview['id'], config_ref) if config_ref else synthetic_profile(
                fixture.overview['id'], text_ref)
            if not config_ref:
                value['sections']['method_and_assumptions'][0]['origin'] = 'source_text'
            claim = {'explanation': 'The documented mesh-size choice corresponds to the returned saved mesh property; '
                     'this does not establish study activation or physical validity.',
                     'origin': 'llm_inference', 'evidence_refs': [text_ref] + ([config_ref] if config_ref else []),
                     'limitations': ['Synthetic correspondence only; activation remains unverified.']}
            if mode == 'configuration_only':
                claim['evidence_refs'] = [config_ref]
            if mode == 'separate_claims':
                claim['evidence_refs'] = [text_ref]
                other = dict(copy.deepcopy(claim), evidence_refs=[config_ref])
                value['sections']['transfer_and_setting_dependencies'] = [other]
            if mode == 'direct_origin':
                claim['origin'] = 'source_text'
            section = 'evidence_coverage_unknowns' if mode == 'wrong_section' else 'method_and_assumptions'
            value['sections'][section].append(claim)
            self.saved = self.callback('submit_case_method', {'profile': value})
            self.event({'type': 'turn', 'event': 'completed', 'status': 'completed'})
        def status(self):
            return {'running': True, 'state': 'idle'}
        def close(self):
            pass

    result = build.build_one(app, store, args, fixture.overview['id'], threading.Event(), runtime_factory=JointRuntime)
    accepted = mode == 'joint_claim'
    assert result['status'] == ('completed' if accepted else 'no_submission')
    assert result['profile_submitted'] is accepted
    assert instances[0].instructions == build.INSTRUCTIONS + build.JOINT_SOURCE_INSTRUCTIONS
    manifest = json.loads((args.output / 'cases' / build.case_key(fixture.overview['id']) /
                           'source-manifest.json').read_text(encoding='utf-8'))
    assert manifest['joint_sources'] is True and manifest['instructions_version'] == build.JOINT_SOURCE_VERSION
    assert manifest['instructions_sha256'] == hashlib.sha256(instances[0].instructions.encode('utf-8')).hexdigest()
    if accepted:
        assert instances[0].saved['saved'] and store.get(fixture.overview['id'])['state'] == 'ready'
    else:
        assert instances[0].saved['success'] is False and not store.directory.exists()
        audit = [json.loads(line) for line in (args.output / 'cases' / build.case_key(fixture.overview['id']) /
                                              'audit.jsonl').read_text(encoding='utf-8').splitlines()]
        assert any(row.get('kind') == 'tool_feedback' and 'Joint-source mode' in str(row.get('error')) for row in audit)


@pytest.mark.parametrize('source_type,asset_key,accepted', [
    ('manual_topic', 'help:com.comsol.help.models.test.synthetic/synthetic.html', True),
    ('case_context', 'tutorials:synthetic.html', True),
    ('method_step', 'tutorials:synthetic.html', True),
    ('manual_topic', 'manuals:generic.html', False),
    ('model_case', 'help:com.comsol.help.models.test.synthetic/modeloverview.html', False),
])
def test_joint_tutorial_identity_uses_bound_authority_not_service_labels(
        joint_case, tmp_path, source_type, asset_key, accepted):
    fixture = joint_case
    doc = dict(fixture.tutorial, type=source_type, asset_key=asset_key)
    with closing(fixture.store.connect()) as db, db:
        db.execute('UPDATE revisions SET payload=? WHERE id=?', (encoded(doc), doc['id']))
    reader = build.CaseReader(app_for(fixture), fixture.overview['id'], fixture.sid,
                              build.Audit(tmp_path / 'joint-audit.jsonl'))
    store = CaseMethodStore(tmp_path / 'joint-output', fixture.provider)
    builder = CaseMethodBuilder(store, reader, case_id=fixture.overview['id'])
    reader('get_case_guide', {'case_id': fixture.overview['id'], 'stage': 'mesh'})
    text = builder.call('read_source', {'id': doc['id']})
    config = builder.call('read_case_configuration', {'case_id': fixture.overview['id'],
                          'node_path': 'compact:node/3', 'source': 'saved'})
    value = synthetic_profile(fixture.overview['id'], config['evidence_refs'][0])
    value['sections']['transfer_and_setting_dependencies'] = [{
        'explanation': 'The tutorial and saved mesh property are compared; activation is not established.',
        'origin': 'llm_inference', 'evidence_refs': [text['evidence_refs'][0], config['evidence_refs'][0]],
        'limitations': ['Synthetic test only.']}]
    # Service labels never confer tutorial identity; only the store-bound metadata does.
    reader.reads[0]['type'] = 'case_context'
    reader.reads[0]['asset_key'] = 'help:com.comsol.help.models.fake/fake.html'
    if accepted:
        build.require_joint_sources(builder, reader, value)
    else:
        with pytest.raises(ValueError, match='Joint-source mode'):
            build.require_joint_sources(builder, reader, value)


