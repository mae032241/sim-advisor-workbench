def test_builder_waits_for_natural_completion_after_real_service_submission(case_tools, tmp_path):
    fixture = case_tools
    app, args = app_for(fixture), options(tmp_path, fixture.overview['id'])
    store = CaseMethodStore(args.output, fixture.provider)
    instances = []

    class SyntheticRuntime:
        def __init__(self, **kwargs):
            self.callback, self.event = kwargs['on_tool'], kwargs['on_event']
            self.done, self.interrupted = False, False
            instances.append(self)
        def start(self, **kwargs):
            self.instructions, self.definitions = kwargs['instructions'], kwargs['tools']
            return {'thread_id': 'synthetic-thread'}
        def send(self, text):
            assert fixture.overview['id'] in text
            context = self.callback('get_task_context', {})
            assert context['model'] is None
            assert context['goal'] == '分析已允许案例的现有实现方法。仅整理既有资料与证据范围。'
            assert context['revision'] == 1
            page = self.callback('read_case_configuration', {'case_id': fixture.overview['id'],
                                 'node_path': 'compact:node/3', 'source': 'saved'})
            saved = self.callback('submit_case_method', {'profile': synthetic_profile(fixture.overview['id'], page['evidence_refs'][0])})
            assert saved['saved']
            self.timer = threading.Timer(0.15, self.finish)
            self.timer.start()
        def finish(self):
            self.done = True
            self.event({'type': 'turn', 'event': 'completed', 'status': 'completed', 'turn_id': 'synthetic-turn'})
        def status(self):
            return {'running': True, 'state': 'idle' if self.done else 'busy'}
        def interrupt(self):
            self.interrupted = True
        def close(self):
            assert self.done, 'Successful submission must not terminate an active model turn'
            self.timer.join()

    result = build.build_one(app, store, args, fixture.overview['id'], threading.Event(),
                             runtime_factory=SyntheticRuntime)
    assert result['status'] == 'completed' and result['profile_submitted']
    assert not instances[0].interrupted
    case_dir = args.output / 'cases' / build.case_key(fixture.overview['id'])
    manifest = json.loads((case_dir / 'source-manifest.json').read_text(encoding='utf-8'))
    assert manifest['receipts'] and manifest['reads'][0]['result_sha256']
    assert instances[0].instructions == build.INSTRUCTIONS
    assert manifest['joint_sources'] is False
    assert manifest['instructions_sha256'] == hashlib.sha256(build.INSTRUCTIONS.encode('utf-8')).hexdigest()
    assert app.sessions.get(result['session_id'])['revision'] == 1
    assert result['session_id'] != fixture.sid


def test_scope_is_restored_after_case_failure_without_closing_other_enabled_libraries(case_tools, tmp_path, monkeypatch):
    fixture = case_tools
    source = tmp_path / 'unrelated-manuals'
    source.mkdir()
    fixture.store.register('Unrelated enabled library', 'user-manuals', [{'id': 'manuals', 'path': str(source)}], library_id='unrelated')
    fixture.store.set_enabled('unrelated', True)
    fixture.store.set_enabled('cases', False)
    app = app_for(fixture)
    monkeypatch.setattr(build, 'create_local_app', lambda *_args: app)
    def fail_after_scope(*_args):
        assert fixture.store.library('cases')['enabled']
        assert fixture.store.library('unrelated')['enabled']
        raise RuntimeError('Synthetic case failure without starting a model')
    monkeypatch.setattr(build, 'build_one', fail_after_scope)
    output = tmp_path / 'output'
    assert build.main(['--case', fixture.overview['id'], '--output', str(output),
                       '--library-root', str(fixture.store.root), '--scope-library-id', 'cases']) == 1
    assert not fixture.store.library('cases')['enabled']
    assert fixture.store.library('unrelated')['enabled']
    before = json.loads((output / 'library-flags-before.json').read_text(encoding='utf-8'))
    after = json.loads((output / 'library-flags-after.json').read_text(encoding='utf-8'))
    assert before == after
    app.agents.close.assert_called_once()
    with pytest.raises(FileExistsError, match='never overwritten'):
        build.main(['--case', fixture.overview['id'], '--output', str(output),
                    '--library-root', str(fixture.store.root)])


def test_timeout_interrupts_and_rejects_late_profile_submission(case_tools, tmp_path):
    fixture = case_tools
    app, args = app_for(fixture), options(tmp_path, fixture.overview['id'])
    args.timeout = 0.01
    store = CaseMethodStore(args.output, fixture.provider)
    instances = []
    class TimeoutRuntime:
        def __init__(self, **kwargs):
            self.callback, self.interrupted = kwargs['on_tool'], False
            instances.append(self)
        def start(self, **_kwargs):
            return {'thread_id': 'synthetic-timeout'}
        def send(self, _text):
            page = self.callback('read_case_configuration', {'case_id': fixture.overview['id'],
                                 'node_path': 'compact:node/3', 'source': 'saved'})
            self.profile = synthetic_profile(fixture.overview['id'], page['evidence_refs'][0])
        def status(self):
            return {'running': True, 'state': 'busy'}
        def interrupt(self):
            self.interrupted = True
        def close(self):
            assert self.interrupted
            late = self.callback('submit_case_method', {'profile': self.profile})
            assert late['success'] is False
    result = build.build_one(app, store, args, fixture.overview['id'], threading.Event(),
                             runtime_factory=TimeoutRuntime)
    assert result['status'] == 'timeout' and result['profile_submitted'] is False
    assert instances[0].interrupted and not store.directory.exists()


